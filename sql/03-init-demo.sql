-- 为全体正式党员生成 2026 年 7/8/9 三个月的党费记录
-- 标准：3000元以下 0.5%，3000-5000 元 1%，5000-10000 元 1.5%，10000 元以上 2%
INSERT INTO `party_dues_record`
(`person_id`, `person_name`, `org_id`, `dues_year`, `dues_month`, `dues_base`, `dues_standard`,
 `dues_paid`, `pay_date`, `pay_type`, `status`)
SELECT
    p.`person_id`, p.`name`, p.`org_id`, 2026, m.`month`,
    mp.`dues_base`,
    ROUND(mp.`dues_base` * CASE
        WHEN mp.`dues_base` < 3000  THEN 0.005
        WHEN mp.`dues_base` < 5000  THEN 0.01
        WHEN mp.`dues_base` < 10000 THEN 0.015
        ELSE 0.02 END, 2) AS std,
    -- 7、8 月已缴清；9 月部分已缴，便于演示"未缴/欠缴"状态
    CASE WHEN m.`month` < 9 OR p.`person_id` % 3 = 0
         THEN ROUND(mp.`dues_base` * CASE
              WHEN mp.`dues_base` < 3000  THEN 0.005
              WHEN mp.`dues_base` < 5000  THEN 0.01
              WHEN mp.`dues_base` < 10000 THEN 0.015
              ELSE 0.02 END, 2)
         ELSE NULL END,
    CASE WHEN m.`month` < 9 OR p.`person_id` % 3 = 0
         THEN STR_TO_DATE(CONCAT('2026-', LPAD(m.`month`, 2, '0'), '-10'), '%Y-%m-%d')
         ELSE NULL END,
    CASE WHEN m.`month` < 9 OR p.`person_id` % 3 = 0 THEN 2 ELSE NULL END,
    CASE WHEN m.`month` < 9 OR p.`person_id` % 3 = 0 THEN 1 ELSE 0 END
FROM `party_person` p
JOIN `party_member_profile` mp ON mp.`person_id` = p.`person_id`
CROSS JOIN (SELECT 7 AS `month` UNION ALL SELECT 8 UNION ALL SELECT 9) m
WHERE p.`member_status` = 5;

